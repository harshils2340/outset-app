type CatalogRow = {
  id: string;
  domain: string;
  name: string;
  website: string | null;
  city: string | null;
  region: string | null;
  metro_id: string | null;
  family: string | null;
  icon_key: string;
  rating: number | null;
  review_count: number | null;
  origin: string;
  lat: number | null;
  lon: number | null;
};

/** Marketplaces and directories are not operators. They never belong in the catalog. */
export const MARKETPLACES = /(^|\.)(sailo|getmyboat|boatsetter|viator|tripadvisor|airbnb|expedia|groupon|yelp|peek|fareharbor|getyourguide|klook|eventbrite|meetup|facebook|instagram|booking|hotels|vrbo|kayak|tours4fun|musement|headout|goldstar|boatbound|clickandboat|samboat|fishingbooker|fishanywhere|guidesly)\.(com|net|co|io|ca)$/i;

const DEFAULT_GAP = "Prices, hours and eligibility are not copied here yet. We will ask when you request.";

function slug(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 48);
}

/** One operator in the shape the guest app's Unclaimed type expects. Facts only, nothing invented. */
function toCatalogItem(r: CatalogRow): Record<string, unknown> {
  const offerings = db
    .prepare("SELECT name, detail, duration, price_cents, price_unit FROM offerings WHERE operator_id = ? ORDER BY price_cents IS NULL, price_cents")
    .all(r.id) as { name: string; detail: string | null; duration: string | null; price_cents: number | null; price_unit: string | null }[];
  const facts = db.prepare("SELECT fact_key, fact_value FROM facts WHERE operator_id = ?").all(r.id) as { fact_key: string; fact_value: string }[];
  const pick = (k: string) => facts.filter((f) => f.fact_key === k).map((f) => f.fact_value);
  const area = r.city ? (r.region && !r.city.includes(r.region) ? r.city + ", " + r.region : r.city) : r.region || "";
  return {
    id: "o-" + slug(r.domain),
    title: r.name,
    cat: r.family || "water",
    art: artFromName(r.name, r.icon_key),
    area,
    metroId: r.metro_id || "",
    src: r.domain,
    rating: r.rating ?? undefined,
    reviews: r.review_count ?? undefined,
    specs: [...pick("spec"), ...pick("requirement"), ...pick("group")].slice(0, 10),
    options: offerings.map((o) => ({
      name: o.name,
      detail: o.duration || o.detail || "",
      price: o.price_cents == null ? null : o.price_cents / 100,
      per: o.price_unit && o.price_unit.startsWith("/") ? o.price_unit : undefined,
    })),
    services: (() => {
      const descs = new Map<string, string>();
      for (const raw of pick("service_desc")) {
        try {
          const d = JSON.parse(raw) as { name: string; desc: string };
          descs.set(d.name.toLowerCase(), d.desc);
        } catch {
          /* ignore */
        }
      }
      const photos = new Map<string, string>();
      for (const raw of pick("service_photo")) {
        try {
          const d = JSON.parse(raw) as { name: string; url: string };
          photos.set(d.name.toLowerCase(), d.url);
        } catch {
          /* ignore */
        }
      }
      const groups = new Map<string, { name: string; desc: string | null; photo?: string; variants: { label: string; price: number | null; per?: string; optionIdx: number }[] }>();
      offerings.forEach((o, idx) => {
        const key = o.name.toLowerCase();
        if (NOT_A_SERVICE.test(o.name)) return;
        const g = groups.get(key) || { name: o.name, desc: descs.get(key) || null, photo: photos.get(key) || undefined, variants: [] };
        g.variants.push({
          label: o.duration || o.detail || "Standard",
          price: o.price_cents == null ? null : o.price_cents / 100,
          per: o.price_unit && o.price_unit.startsWith("/") ? o.price_unit : undefined,
          optionIdx: idx,
        });
        groups.set(key, g);
      });
      return [...groups.values()].filter((g) => !/gift ?cards?|gift certificate|deposit|membership|season pass/i.test(g.name)).slice(0, 14);
    })(),
    includes: uniq(pick("includes").map(cleanLine)).filter(isTidyLine).filter((l) => !/gift ?card|gift certificate|will be provided upon|directions will|upon purchas/i.test(l)).slice(0, 10),
    addons: pick("addon")
      .map((a) => {
        const m = a.match(/^(.*?)\s*\$(\d+(?:\.\d+)?)$/);
        return m ? { name: m[1].trim().replace(/\s+(for|at|only|just|from|is)$/i, ""), detail: "", price: Number(m[2]) } : null;
      })
      .filter((a): a is { name: string; detail: string; price: number } => !!a)
      // "An additional $35" is a fee sentence, not something a guest adds to a cart.
      .filter((a) => a.name.length >= 3 && !/^(an?|the|plus|extra|additional|only|just|from|starting|starts|add|adds|is|are|and|or|for)\b/i.test(a.name) && !/\b(fee|surcharge|deposit|tax|gratuity|tip|per person|per hour)\b/i.test(a.name))
      .slice(0, 6),
    // The honest gap line. Once the widget or crawl gave real rules and policies, say those instead of "not copied yet".
    gap: pick("published_gap")[0] || pick("cancellation")[0] || (pick("policy").length || pick("requirement").length ? [...pick("policy")].slice(0, 3).join(" ") || "Ask the operator about cancellations." : DEFAULT_GAP),
    blurb: pick("description")[0] || pick("site_desc")[0] || pick("one_line")[0] || undefined,
    cover: pick("cover")[0] || undefined,
    photos: [...new Set(pick("photo"))].slice(0, 8),
    ytVideos: pick("yt_video")
      .map((raw) => {
        try {
          const v = JSON.parse(raw) as { id: string; title: string; views: number };
          return { id: v.id, title: v.title, views: v.views };
        } catch {
          return null;
        }
      })
      .filter((v): v is { id: string; title: string; views: number } => !!v)
      .slice(0, 3),
    tiktok: pick("tiktok_profile")[0] || undefined,
    instagram: pick("social:instagram")[0] || undefined,
    video: pick("video")[0] || undefined,
    videoEmbed: pick("video_embed")[0] || undefined,
    lat: r.lat ?? undefined,
    lon: r.lon ?? undefined,
    tags: [...new Set([...pick("google_category"), ...pick("service"), ...offerings.map((o) => o.name)])].slice(0, 12),
    extraNote: pick("extra")[0] || [...pick("policy"), ...pick("checkin"), ...pick("meeting_point"), ...pick("season")].join(" · ").slice(0, 700) || undefined,
    // Viator-shaped sections. Each only appears when the site said it.
    highlights: uniq(pick("spec").map(cleanLine)).filter(isTidyLine).slice(0, 8),
    requirements: collapseRules(uniq(pick("requirement").map(cleanLine)).filter(isTidyLine)).slice(0, 10),
    groupInfo: uniq(pick("group").map(cleanLine)).slice(0, 5),
    bring: uniq(pick("bring").map(cleanLine)).slice(0, 8),
    season: cleanLine(pick("season")[0] || "") || undefined,
    meetingPoint: cleanLine(pick("meeting_point")[0] || "") || undefined,
    checkin: cleanPara(pick("checkin")[0] || "") || undefined,
    cancellation: cleanPara(pick("cancellation")[0] || "") || cleanPara(pick("policy").filter((l) => /cancel|refund/i.test(l)).join(" ")) || undefined,
    policies: uniq(pick("policy").map(cleanLine)).filter(isTidyLine).filter((l) => !/gift ?card|gift certificate/i.test(l)).slice(0, 8),
    waiverUrl: pick("waiver_url").find((u) => /^https?:\/\/\S+$/.test(u) && !/\/w\/?$/.test(u)) || undefined,
    hoursText: uniq(pick("hours_text").map((h) => cleanLine(h.replace(/^hours(?: & admission)?\s*/i, "")))).slice(0, 3),
    faq: pick("faq").map(parseFaq).filter((f): f is { q: string; a: string } => !!f).slice(0, 8),
    dur: durationOf(offerings.map((o) => o.duration || o.detail || "")) || undefined,
    fc: freeCancel(cleanPara(pick("cancellation")[0] || "") || pick("policy").filter((l) => /cancel|refund/i.test(l)).join(" ")) || undefined,
  };
}

/** "2 hours", "90 min", "1 to 4 hours": the first duration the menu states. */
function durationOf(texts: string[]): string | null {
  for (const t of texts) {
    const m = t.match(/\b(\d+(?:\.\d+)?)\s*(?:-|to)?\s*(\d+)?\s*(hours?|hrs?|minutes?|mins?|days?)\b/i);
    if (!m) continue;
    const n = Number(m[2] || m[1]);
    const unit = /min/i.test(m[3]) ? "min" : /day/i.test(m[3]) ? (n === 1 ? "day" : "days") : n === 1 ? "hour" : "hours";
    return (m[2] ? m[1] + " to " + m[2] : m[1]) + " " + unit;
  }
  return null;
}

/** "Free cancellation up to 48 hours before", only when the operator's own words promise a full refund. */
function freeCancel(text: string): string | null {
  if (!text || !/full refund|free cancellation|100% refund|fully refundable/i.test(text)) return null;
  if (/non-?refundable|no refunds?\b/i.test(text) && !/full refund/i.test(text)) return null;
  const m = text.match(/(\d+)\s*(hours?|hrs?|days?)/i);
  if (!m) return "Free cancellation";
  const n = Number(m[1]);
  const unit = /day/i.test(m[2]) ? (n === 1 ? "day" : "days") : n === 1 ? "hour" : "hours";
  return "Free cancellation up to " + n + " " + unit + " before";
}

/** "Hawaiian Parasail" is parasailing whatever OpenStreetMap tagged it. The name wins when it names the activity outright. */
const ART_BY_NAME: [RegExp, string][] = [
  [/\bparasail/i, "parasail"],
  [/\bjet ?ski|waverunner|sea-?doo/i, "jetski"],
  [/\bskydiv|\btandem jump|\bparachut/i, "skydive"],
  [/\baxe|\bhatchet/i, "axe"],
  [/\bescape (room|game)|\bescape\b/i, "escape"],
  [/\bkart|\bkarting/i, "kart"],
  [/\bpaintball|\bairsoft|\blaser tag/i, "paintball"],
  [/\bhelicopter|\bheli\b|\bhelitour/i, "heli"],
  [/\bballoon/i, "balloon"],
  [/\bkayak|\bpaddle ?board|\bcanoe|\bsup\b|\bpaddl/i, "kayak"],
  [/\bpontoon/i, "pontoon"],
  [/\bhorse|\bequestrian|\btrail ride|\bstable/i, "horse"],
  [/\bfishing|\bcharter fish|\bsportfish|\bangl/i, "fishing"],
  [/\bsunset (cruise|sail)|\bcruise|\bsailing|\bcatamaran|\byacht/i, "cruise"],
];
function artFromName(name: string, fallback: string): string {
  for (const [re, art] of ART_BY_NAME) if (re.test(name)) return art;
  return fallback;
}

/** One clean statement: not a question, not a mashed paragraph, not a scraped aside. */
/** "Must be 21 with ID" and "All participants must be age 21 or older with a valid ID" say one thing. Keep the shortest per topic. */
function collapseRules(lines: string[]): string[] {
  const byKey = new Map<string, string>();
  const order: string[] = [];
  for (const l of lines) {
    const nums = (l.match(/\d+/g) || []).join(",");
    const topic = /\b(age|years?|old|older|minor|child|kid|adult|\d+\s*\+)\b/i.test(l) ? "age" : /\b(weight|lbs?|pounds?|kg)\b/i.test(l) ? "weight" : /\b(height|tall|inches|cm)\b/i.test(l) ? "height" : /\b(licen[cs]e|permit|boater)\b/i.test(l) ? "license" : "";
    const key = topic && nums ? topic + ":" + nums : l.toLowerCase();
    const cur = byKey.get(key);
    if (!cur) {
      byKey.set(key, l);
      order.push(key);
    } else if (l.length < cur.length) byKey.set(key, l);
  }
  return order.map((k) => byKey.get(k)!);
}

function isTidyLine(l: string): boolean {
  if (l.length < 6 || l.length > 150) return false;
  if (/\?\s*$/.test(l) || /\?\s+[A-Z]/.test(l)) return false;
  if (/^(and|but|or|so|also|please note|note:|p\.s\.)\b/i.test(l)) return false;
  if (/\b(duration|meeting location|rates?)\b.*\$\d/i.test(l)) return false;
  if (/not limited to|click|subscribe|newsletter|follow us/i.test(l)) return false;
  return true;
}

/** Things a site sells that a guest does not book a time for. */
const NOT_A_SERVICE = /\b(gift ?cards?|gift certificates?|e-?gift|merch(andise)?|t-?shirts?|hats?|apparel|donation|membership|season pass|parking)\b/i;

function uniq(list: string[]): string[] {
  const seen = new Set<string>();
  return list.filter((x) => x && !seen.has(x.toLowerCase()) && (seen.add(x.toLowerCase()), true));
}

/** Markdown, image tags and widget leftovers out; one clean sentence in. */
function cleanLine(raw: string): string {
  return raw
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/[#*_>`]+/g, " ")
    .replace(/https?:\/\/\S+/g, "")
    .replace(/^\s*(?:\(?\d{1,2}[.)]|[-–•·]|[a-z][.)])\s+/i, "")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 240);
}

function cleanPara(raw: string): string {
  const flat = raw
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/[#*_>`]+/g, " ")
    .replace(/https?:\/\/\S+/g, "")
    .replace(/\s+/g, " ")
    .trim();
  // Sites repeat the same sentence in two places. Keep each once, and never cut mid-sentence.
  const seen = new Set<string>();
  const out: string[] = [];
  let len = 0;
  for (const sentence of flat.split(/(?<=[.!?])\s+(?=[A-Z0-9"(])/)) {
    const key = sentence.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
    if (!key || seen.has(key)) continue;
    if (len + sentence.length > 700) break;
    seen.add(key);
    out.push(sentence);
    len += sentence.length + 1;
  }
  if (out.length > 1 && !/[.!?)"]$/.test(out[out.length - 1])) out.pop();
  return out.join(" ");
}

/** FAQ facts come as "Question? >Answer" or "Question? Answer". Anything without a question mark is not a FAQ. */
function parseFaq(raw: string): { q: string; a: string } | null {
  const t = cleanPara(raw);
  const i = t.indexOf("?");
  if (i < 8 || i > 160) return null;
  // The question is the last sentence before the question mark.
  const before = t.slice(0, i + 1);
  const qStart = Math.max(before.lastIndexOf(". "), before.lastIndexOf("! "), -2) + 2;
  const q = before.slice(qStart).replace(/^[\s\-–—•·:]+/, "").trim();
  const a = t.slice(i + 1).replace(/^\s*>\s*/, "").trim();
  if (q.length < 8 || a.length < 12) return null;
  return { q, a: a.slice(0, 500) };
}

/** Write public/catalog.json: every real operator plus its contact facts. The app fetches it at startup. */
export function syncCatalogToApp(): { path: string; count: number } {
  const rows = db
    .prepare(
      `SELECT id, domain, name, website, city, region, metro_id, family, icon_key, rating, review_count, origin, lat, lon
       FROM operators WHERE origin != 'demo' AND name IS NOT NULL AND length(name) >= 3
       ORDER BY completeness DESC, name ASC`,
    )
    .all() as CatalogRow[];
  const full = rows.filter((r) => !MARKETPLACES.test(r.domain)).map(toCatalogItem);
  const contactByDomain: Record<string, OperatorContact> = {};
  for (const c of allContacts()) contactByDomain[c.domain] = c;

  // One small file per operator with everything: services, photos, videos, facts, contact.
  const dir = join(appDataDir, "../../public/o");
  mkdirSync(dir, { recursive: true });
  const keep = new Set<string>();
  for (const item of full) {
    const c = contactByDomain[String(item.src)];
    const contact = c
      ? { domain: c.domain, phone: c.phone, street: c.street, city: c.city, region: c.region, postal: c.postal, hours: c.hours }
      : undefined;
    const file = item.id + ".json";
    keep.add(file);
    writeFileSync(join(dir, file), JSON.stringify({ ...item, contact }));
  }
  for (const f of readdirSync(dir)) if (!keep.has(f)) unlinkSync(join(dir, f));

  // The browse catalog carries only what cards, rails and search need. Details load per listing.
  const operators = full.map((item) => {
    const options = (item.options as { price: number | null }[]) || [];
    const priced = options.map((o) => o.price).filter((n): n is number => n != null);
    return {
      id: item.id, title: item.title, cat: item.cat, art: item.art, area: item.area, metroId: item.metroId, src: item.src,
      rating: item.rating, reviews: item.reviews, lat: item.lat, lon: item.lon, cover: item.cover, video: item.video,
      tags: ((item.tags as string[]) || []).slice(0, 6),
      from: priced.length ? Math.min(...priced) : undefined,
      dur: item.dur, fc: item.fc,
      options: [], specs: [], includes: [], gap: "", lite: true,
    };
  });
  const path = join(appDataDir, "../../public/catalog.json");
  writeFileSync(path, JSON.stringify({ generatedAt: new Date().toISOString(), operators, contacts: {} }));
  const pages = writeLandingPages(full as never);
  console.log("Wrote " + pages.pages + " landing pages to public/p");
  return { path, count: operators.length };
}
