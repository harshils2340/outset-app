import { createContext, useContext } from "react";
import type { Unclaimed } from "../../data/types";
import type { OpBooking, OpStatus, OperatorProfile } from "../../lib/operator";

export type OpPage = "home" | "bookings" | "calendar" | "services" | "hours" | "listing" | "assistant" | "payouts" | "settings";

export type OpApi = {
  p: OperatorProfile;
  u: Unclaimed;
  compact: boolean;
  page: OpPage;
  go: (page: OpPage) => void;
  /** Patch the profile. Saves to device and pushes edits to the guest listing. */
  set: (patch: Partial<OperatorProfile> | ((p: OperatorProfile) => OperatorProfile)) => void;
  bookings: OpBooking[];
  decide: (b: OpBooking, status: OpStatus) => void;
  openBooking: (id: string | null) => void;
  openedId: string | null;
  preview: () => void;
  toast: (t: string) => void;
  logout: () => void;
};

export const OpCtx = createContext<OpApi | null>(null);

export function useOp(): OpApi {
  const v = useContext(OpCtx);
  if (!v) throw new Error("useOp must run inside the operator shell");
  return v;
}

